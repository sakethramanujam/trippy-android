/** Actions the list hands up to the shell, so later features can slot in without new plumbing. */
class TripsListActions(
    val open: (Int) -> Unit = {},
    val refresh: suspend () -> Unit = {},
    val account: () -> Unit = {},
    val search: () -> Unit = {},
)

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun TripsScreen(
    state: TripsState,
    initials: String,
    now: LocalDateTime,
    actions: TripsListActions,
    journeyTripIds: Set<Int> = emptySet(),
    journeysSection: LazyListScope.(row: @Composable (TripSnapshot, @Composable () -> Unit) -> Unit) -> Unit = {},
    row: @Composable (TripSnapshot, @Composable () -> Unit) -> Unit = { _, content -> content() },
) {
    val snaps = remember(state.trips, state.rentals, now.toLocalDate()) { state.trips.map { TripSnapshot(it, state.rentals, now) } }
    val sections = remember(snaps, journeyTripIds) { TripSections.of(snaps, journeyTripIds) }
    val scope = rememberCoroutineScope()
    val list = rememberLazyListState()
    val hero = sections.hero
    val art = remember(hero) { hero?.stops?.mapNotNull { s -> s.coordinate?.let { ArtStop(s.code, it) } }.orEmpty() }

    Box(Modifier.fillMaxSize().background(TColor.canvas)) {
        RouteArt(art, Modifier.fillMaxWidth().height(330.dp), topInset = 70.dp, bottomInset = 100.dp)
        PullToRefreshBox(isRefreshing = state.refreshing && state.loaded, onRefresh = { scope.launch { actions.refresh() } }) {
            LazyColumn(state = list, modifier = Modifier.fillMaxSize()) {
                item { Spacer(Modifier.height(if (hero != null) 260.dp else 120.dp)) }
                item(key = "header") { SheetHeader(snaps, initials, state, actions) }
                if (!state.loaded) {
                    item { Box(Modifier.sheet().fillMaxWidth().padding(48.dp), Alignment.Center) { CircularProgressIndicator(color = TColor.coral) } }
                } else if (snaps.isEmpty()) {
                    item { EmptyTrips() }
                } else {
                    hero?.let { h -> item(key = "hero") { Box(Modifier.sheet()) { row(h) { UpNext(h, now, actions) } } } }
                    section("Pinned", sections.pinned, now, actions, row, pinned = true)
                    journeysSection(row)
                    section("Now", sections.now, now, actions, row)
                    section("Upcoming", sections.upcoming, now, actions, row)
                    sections.pastByYear.forEach { (year, trips) -> section(if (year == 0) "Undated" else "$year", trips, now, actions, row) }
                }
                item { Box(Modifier.sheet().fillMaxWidth().height(120.dp)) }
            }
        }
        // Once the sheet reaches the top, keep the status bar readable over scrolled rows.
        if (list.firstVisibleItemIndex > 0) {
            Box(Modifier.fillMaxWidth().windowInsetsTopHeight(WindowInsets.statusBars).background(TColor.surfaceSheet))
        }
    }
}

/** Every list item paints the sheet's background so the art only shows above the sheet. */
internal fun Modifier.sheet(): Modifier = this.fillMaxWidth().background(TColor.surfaceSheet)

@Composable
private fun SheetHeader(snaps: List<TripSnapshot>, initials: String, state: TripsState, actions: TripsListActions) {
    Column(
        Modifier.fillMaxWidth().clip(RoundedCornerShape(topStart = 28.dp, topEnd = 28.dp)).background(TColor.surfaceSheet)
            .padding(horizontal = 20.dp).padding(top = 8.dp, bottom = 8.dp),
    ) {
        Box(Modifier.align(Alignment.CenterHorizontally).size(width = 36.dp, height = 5.dp).background(TColor.surfaceHigh, CircleShape))
        Row(Modifier.fillMaxWidth().padding(top = 14.dp), verticalAlignment = Alignment.CenterVertically) {
            Text("My Trips", style = TType.largeTitle, color = TColor.textPrimary, modifier = Modifier.weight(1f))
            RoundButton(onClick = actions.search) { Icon(Icons.Filled.Search, "Search", tint = TColor.textPrimary, modifier = Modifier.size(20.dp)) }
            Spacer(Modifier.width(10.dp))
            RoundButton(onClick = actions.account, color = TColor.coral) { Text(initials, style = TType.footnoteStrong, color = Color.White) }
        }
        if (snaps.isNotEmpty()) Text(statsLine(snaps), style = TType.callout, color = TColor.textSecondary, modifier = Modifier.padding(top = 2.dp))
        if (state.offline) Row(Modifier.padding(top = 10.dp), verticalAlignment = Alignment.CenterVertically) {
            Icon(Icons.Filled.CloudOff, null, tint = TColor.orange, modifier = Modifier.size(14.dp))
            Spacer(Modifier.width(6.dp))
            Text(Fmt.offlineLine(state.lastSynced, System.currentTimeMillis()), style = TType.footnote, color = TColor.orange)
        }
        state.error?.let { FormBanner(it, Modifier.padding(top = 10.dp)) }
    }
}

@Composable
internal fun RoundButton(onClick: () -> Unit, color: Color = TColor.surfaceRaised, content: @Composable () -> Unit) {
    Box(Modifier.size(38.dp).clip(CircleShape).background(color).plainClick(onClick), Alignment.Center) { content() }
}

@Composable
private fun UpNext(s: TripSnapshot, now: LocalDateTime, actions: TripsListActions) {
    val happening = s.phase == TripPhase.NOW
    Column(Modifier.fillMaxWidth().plainClick { actions.open(s.id) }.padding(horizontal = 20.dp).padding(top = 14.dp)) {
        Row(verticalAlignment = Alignment.CenterVertically) {
            Pill(if (happening) "Happening now" else "Up next", TColor.amber)
            Spacer(Modifier.weight(1f))
            s.dateRange()?.let { Text(it, style = TType.footnote, color = TColor.textSecondary) }
        }
        Row(Modifier.padding(top = 12.dp, bottom = 16.dp), verticalAlignment = Alignment.CenterVertically) {
            Column(Modifier.widthIn(min = 92.dp)) {
                Text(if (happening) "${s.dayOfTrip(now)}" else "${s.countdownDays(now)}", style = TType.hero, color = TColor.textPrimary)
                Text(
                    if (happening) "DAY OF ${s.days ?: 1}" else if (s.countdownDays(now) == 1) "DAY TO GO" else "DAYS TO GO",
                    style = TType.label, color = TColor.textSecondary,
                )
            }
            Spacer(Modifier.width(16.dp))
            Column(Modifier.weight(1f)) {
                Text(s.trip.displayTitle, style = TType.title2, color = TColor.textPrimary, maxLines = 2, overflow = TextOverflow.Ellipsis)
                Text(s.routeCodes, style = TType.callout, color = TColor.textSecondary, maxLines = 1, overflow = TextOverflow.Ellipsis)
                Spacer(Modifier.height(6.dp))
                if (s.events.isEmpty()) Text("Nothing booked", style = TType.footnote, color = TColor.textTertiary)
                else TripChips(s)
            }
            Icon(Icons.AutoMirrored.Filled.KeyboardArrowRight, null, tint = TColor.textTertiary)
        }
        HorizontalDivider(color = TColor.divider)
    }
}

private fun LazyListScope.section(
    title: String, trips: List<TripSnapshot>, now: LocalDateTime, actions: TripsListActions,
    row: @Composable (TripSnapshot, @Composable () -> Unit) -> Unit, pinned: Boolean = false,
) {
    if (trips.isEmpty()) return
    item(key = "h-$title") { SectionHeader(title, "${trips.size} TRIP${if (trips.size == 1) "" else "S"}") }
    items(trips, key = { "t-$title-${it.id}" }) { s ->
        Box(Modifier.sheet()) { row(s) { TripRow(s, now, pinned, actions) } }
    }
}

@Composable
internal fun SectionHeader(title: String, trailing: String?) {
    Row(Modifier.sheet().padding(start = 20.dp, end = 20.dp, top = 26.dp, bottom = 8.dp), verticalAlignment = Alignment.Bottom) {
        Text(title, style = TType.title3, color = TColor.textPrimary, modifier = Modifier.weight(1f))
        trailing?.let { Text(it, style = TType.micro, color = TColor.textSecondary) }
    }
}

@Composable
fun TripRow(s: TripSnapshot, now: LocalDateTime, pinned: Boolean, actions: TripsListActions) {
    Column(Modifier.background(TColor.surfaceSheet).plainClick { actions.open(s.id) }) {
        HorizontalDivider(color = TColor.divider, modifier = Modifier.padding(horizontal = 20.dp))
        Row(Modifier.fillMaxWidth().padding(horizontal = 20.dp, vertical = 12.dp), verticalAlignment = Alignment.CenterVertically) {
            Column(Modifier.width(52.dp), horizontalAlignment = Alignment.CenterHorizontally) {
                Text("${s.days ?: "–"}", style = TType.title, color = TColor.textPrimary)
                Text(if (s.days == 1) "DAY" else "DAYS", style = TType.micro, color = TColor.textSecondary)
            }
            Spacer(Modifier.width(14.dp))
            Column(Modifier.weight(1f)) {
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Text(s.routeCodes, style = TType.footnote, color = TColor.textSecondary, maxLines = 1, overflow = TextOverflow.Ellipsis, modifier = Modifier.weight(1f))
                    s.dateRange()?.let { Text(it, style = TType.footnote, color = TColor.textSecondary) }
                    if (pinned) Icon(Icons.Filled.PushPin, "Pinned", tint = TColor.coral, modifier = Modifier.padding(start = 4.dp).size(13.dp))
                }
                Row(verticalAlignment = Alignment.CenterVertically, horizontalArrangement = Arrangement.spacedBy(6.dp)) {
                    Text(s.trip.displayTitle, style = TType.headline, color = TColor.textPrimary, maxLines = 1, overflow = TextOverflow.Ellipsis, modifier = Modifier.weight(1f, fill = false))
                    if (s.trip.isAutoGenerated) AutoTag()
                }
                if (s.phase == TripPhase.UPCOMING) {
                    val d = s.countdownDays(now)
                    Text(if (d == 0) "Starts today" else "In $d day${if (d == 1) "" else "s"}", style = TType.caption, color = TColor.coral)
                }
                Spacer(Modifier.height(4.dp))
                TripChips(s)
            }
        }
    }
}

@Composable
private fun EmptyTrips() {
    Column(Modifier.sheet().padding(32.dp), horizontalAlignment = Alignment.CenterHorizontally) {
        Text("No trips yet", style = TType.title3, color = TColor.textPrimary)
        Text("Trips you create on the web or the iPhone app show up here.", style = TType.callout, color = TColor.textSecondary, modifier = Modifier.padding(top = 6.dp))
    }
}
