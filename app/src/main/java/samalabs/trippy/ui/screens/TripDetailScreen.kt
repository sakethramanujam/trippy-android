@Composable
fun Timeline(events: List<TripEvent>, now: LocalDateTime, actions: TripDetailActions) {
    Column {
        events.forEachIndexed { i, e ->
            val prev = events.getOrNull(i - 1)
            val newDay = i == 0 || (prev?.date?.toLocalDate() != e.date?.toLocalDate())
            if (newDay) Row(Modifier.padding(top = 10.dp, bottom = 6.dp), verticalAlignment = Alignment.CenterVertically) {
                Text(e.date?.let { Fmt.dayYear(it).uppercase() } ?: "UNSCHEDULED", style = TType.label, color = TColor.textSecondary)
                HorizontalDivider(Modifier.padding(start = 8.dp), color = TColor.divider)
            }
            EventRow(e, now, isLast = i == events.lastIndex, onClick = { actions.openEvent(e) })
        }
    }
}

@Composable
private fun EventRow(e: TripEvent, now: LocalDateTime, isLast: Boolean, onClick: () -> Unit) {
    val done = e.date?.let { !it.isAfter(now) } ?: false
    Row(Modifier.fillMaxWidth().height(IntrinsicSize.Min).plainClick(onClick)) {
        Column(Modifier.width(14.dp).fillMaxHeight(), horizontalAlignment = Alignment.CenterHorizontally) {
            Box(Modifier.padding(top = 4.dp).size(12.dp).clip(CircleShape).background(if (done) TColor.green else e.kind.color).border(2.dp, TColor.surfaceSheet, CircleShape))
            Box(Modifier.width(2.dp).weight(1f).background(if (isLast) Color.Transparent else TColor.divider))
        }
        Column(Modifier.weight(1f).padding(start = 12.dp, bottom = if (isLast) 4.dp else 18.dp)) {
            Row(verticalAlignment = Alignment.CenterVertically) {
                when {
                    e.flight != null -> BrandTile(Brands.carrierCode(e.flight), Brands.flight(e.flight), size = 18)
                    e.rental != null -> BrandTile(e.rental.company.orEmpty().ifEmpty { "R" }, Brands.rental(e.rental), size = 18)
                    else -> Icon(e.kind.icon, null, tint = e.kind.color, modifier = Modifier.size(16.dp))
                }
                Text(e.micro, style = TType.label, color = TColor.textSecondary, maxLines = 1, overflow = TextOverflow.Ellipsis, modifier = Modifier.weight(1f).padding(start = 6.dp))
                if (e.code.isNotEmpty()) Text(e.code, style = TType.footnoteStrong, color = TColor.textPrimary.copy(alpha = 0.9f))
            }
            Text(e.title, style = TType.headline, color = TColor.textPrimary, maxLines = 1, overflow = TextOverflow.Ellipsis, modifier = Modifier.padding(top = 3.dp))
            Row(verticalAlignment = Alignment.CenterVertically) {
                val t = e.date?.let { Fmt.time(it) }
                if (t != null) {
                    val parts = t.split(" ")
                    Text(parts[0], style = TType.heroSmall, color = if (done) TColor.green else TColor.textPrimary)
                    Text(" " + parts.getOrElse(1) { "" }, style = TType.numberSmall, color = if (done) TColor.green else TColor.textPrimary, modifier = Modifier.padding(top = 10.dp))
                } else Text("—", style = TType.largeTitle, color = TColor.textTertiary)
                Spacer(Modifier.weight(1f))
                e.highlight?.takeIf { it.isNotBlank() }?.let { HighlightBlock(it, e.highlightKind?.icon) }
            }
            e.subtitle?.takeIf { it.isNotBlank() }?.let { Text(it, style = TType.footnote, color = TColor.textSecondary, maxLines = 2) }
        }
        if (e.rental != null || e.flight != null || e.lodging != null) {
            Icon(Icons.AutoMirrored.Filled.KeyboardArrowRight, null, tint = TColor.textTertiary, modifier = Modifier.padding(top = 30.dp))
        }
    }
}

private data class Tile(val icon: ImageVector, val label: String, val value: String, val caption: String?, val tint: Color = Color.White)

@Composable
private fun GoodToKnow(s: TripSnapshot) {
    val t = s.trip
    val stays = t.activeLodgings
    val tiles = buildList {
        s.days?.let { add(Tile(Icons.Filled.CalendarMonth, "Duration", if (it == 1) "1 day" else "$it days", s.dateRange())) }
        add(Tile(Icons.Filled.Place, "Places", "${s.stops.map { it.code }.toSet().size}",
            if (s.stops.isEmpty()) "None yet" else s.stops.map { it.city ?: it.code }.distinct().take(3).joinToString(", ")))
        val bookings = t.expenses.isEmpty()
        add(Tile(Icons.Filled.CreditCard, if (bookings) "Bookings" else "Spent", Fmt.compactMoney(s.spend),
            if (bookings) (if (stays.isEmpty()) "Rental & flight totals" else "Flights, stays & cars") else "${t.expenses.size} expense${if (t.expenses.size == 1) "" else "s"}", TColor.green))
        add(Tile(Icons.Filled.Group, "Travelers", "${t.participants.size}",
            if (t.participants.isEmpty()) "Add people to split" else t.participants.take(3).joinToString(", ") { it.name.substringBefore(" ") }))
        val booked = buildList {
            if (t.flights.isNotEmpty()) add("${t.flights.size} flight${if (t.flights.size == 1) "" else "s"}")
            if (s.rentals.isNotEmpty()) add("${s.rentals.size} car${if (s.rentals.size == 1) "" else "s"}")
            if (stays.isNotEmpty()) add("${stays.size} stay${if (stays.size == 1) "" else "s"}")
            if (t.activities.isNotEmpty()) add("${t.activities.size} plan${if (t.activities.size == 1) "" else "s"}")
        }
        if (booked.isNotEmpty()) add(Tile(Icons.Filled.Checklist, "Booked", "${t.flights.size + stays.size + s.rentals.size + t.activities.size}", booked.joinToString(" · ")))
        if (stays.isNotEmpty()) add(Tile(Icons.Filled.Hotel, "Nights", "${stays.sumOf { it.nightTotal }}", stays.map { it.displayName }.distinct().take(2).joinToString(", "), TColor.coral))
        val flown = t.flights.sumOf { it.distanceMiles ?: 0.0 }
        val driven = s.rentals.sumOf { it.milesDriven ?: 0.0 }
        if (flown + driven > 0) add(Tile(Icons.Filled.Route, "Distance", "${Fmt.number(flown + driven)} mi",
            listOfNotNull(if (flown > 0) "${Fmt.number(flown)} flown" else null, if (driven > 0) "${Fmt.number(driven)} driven" else null).joinToString(" · ")))
    }
    Column(verticalArrangement = Arrangement.spacedBy(10.dp)) {
        tiles.chunked(2).forEach { row ->
            Row(horizontalArrangement = Arrangement.spacedBy(10.dp)) {
                row.forEach { TileView(it, Modifier.weight(1f)) }
                if (row.size == 1) Spacer(Modifier.weight(1f))
            }
        }
    }
}

@Composable
private fun TileView(t: Tile, modifier: Modifier) {
    Column(
        modifier.clip(RoundedCornerShape(20.dp)).background(Color.White.copy(alpha = 0.03f))
            .border(1.dp, Color.White.copy(alpha = 0.10f), RoundedCornerShape(20.dp)).padding(16.dp),
    ) {
        Row(verticalAlignment = Alignment.CenterVertically) {
            Icon(t.icon, null, tint = TColor.textSecondary, modifier = Modifier.size(12.dp))
            Text(" " + t.label.uppercase(), style = TType.label, color = TColor.textSecondary)
        }
        Text(t.value, style = TType.number, color = t.tint, maxLines = 1, modifier = Modifier.padding(top = 4.dp))
        Text(t.caption ?: " ", style = TType.caption, color = TColor.textSecondary, maxLines = 1, overflow = TextOverflow.Ellipsis)
    }
}
