data class MenuAction(val label: String, val icon: ImageVector, val destructive: Boolean = false, val run: () -> Unit)

class TripDetailActions(
    val close: () -> Unit,
    val openEvent: (TripEvent) -> Unit = {},
    val openJourney: (Int) -> Unit = {},
    val menu: List<MenuAction> = emptyList(),
    val headerButtons: @Composable () -> Unit = {},
    /** Extra sections other features add (expenses, stories rail...). */
    val extraSections: @Composable () -> Unit = {},
)

@Composable
fun TripDetailScreen(snap: TripSnapshot, journey: ApiJourney?, now: LocalDateTime, actions: TripDetailActions) {
    val scroll = rememberScrollState()
    val art = remember(snap) { snap.stops.mapNotNull { s -> s.coordinate?.let { ArtStop(s.code, it) } } }
    Box(Modifier.fillMaxSize().background(TColor.canvas)) {
        RouteArt(art, Modifier.fillMaxWidth().height(340.dp), topInset = 60.dp, bottomInset = 90.dp)
        Column(Modifier.fillMaxSize().verticalScroll(scroll)) {
            Spacer(Modifier.height(280.dp))
            Column(
                Modifier.fillMaxWidth().clip(RoundedCornerShape(topStart = 28.dp, topEnd = 28.dp)).background(TColor.surfaceSheet)
                    .padding(horizontal = 20.dp).padding(top = 8.dp, bottom = 120.dp),
                verticalArrangement = Arrangement.spacedBy(28.dp),
            ) {
                Column {
                    Box(Modifier.align(Alignment.CenterHorizontally).size(width = 36.dp, height = 5.dp).background(TColor.surfaceHigh, CircleShape))
                    Header(snap, actions)
                    Spacer(Modifier.height(14.dp))
                    TripStatus(snap, now)
                    journey?.let { JourneyLink(it, snap.id, actions); }
                }
                Travelers(snap)
                Column {
                    SectionTitle("Itinerary", if (snap.events.isEmpty()) null else "${snap.events.size} events")
                    if (snap.events.isEmpty()) Text("Nothing booked yet. Forward confirmations to your Trippy inbox or add them on the web.", style = TType.callout, color = TColor.textSecondary)
                    Timeline(snap.events, now, actions)
                }
                Column {
                    SectionTitle("Good to Know")
                    GoodToKnow(snap)
                }
                actions.extraSections()
                if (snap.trip.isAutoGenerated) {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Icon(Icons.Filled.AutoAwesome, null, tint = TColor.textSecondary, modifier = Modifier.size(15.dp))
                        Text("  Auto-generated from your rental history", style = TType.footnote, color = TColor.textSecondary)
                    }
                }
            }
        }
        if (scroll.value > 400) Box(Modifier.fillMaxWidth().windowInsetsTopHeight(WindowInsets.statusBars).background(TColor.surfaceSheet))
    }
}

private fun headerMicro(s: TripSnapshot): String = buildList {
    if (s.trip.isAutoGenerated) add("AUTO")
    add(if (s.phase == TripPhase.NOW) "ON TRIP" else s.phase.label.uppercase())
    s.dateRange(withYear = true)?.let { add(it.uppercase()) }
}.joinToString(" • ")

@Composable
private fun Header(s: TripSnapshot, actions: TripDetailActions) {
    var menu by remember { mutableStateOf(false) }
    Row(Modifier.fillMaxWidth().padding(top = 12.dp), verticalAlignment = Alignment.CenterVertically) {
        Column(Modifier.weight(1f)) {
            Text(headerMicro(s), style = TType.label, color = TColor.textSecondary, maxLines = 1, overflow = TextOverflow.Ellipsis)
            Text(s.trip.displayTitle, style = TType.title, color = TColor.textPrimary, maxLines = 2, overflow = TextOverflow.Ellipsis)
        }
        Row(horizontalArrangement = Arrangement.spacedBy(10.dp)) {
            actions.headerButtons()
            if (actions.menu.isNotEmpty()) Box {
                CircleIcon(Icons.Filled.MoreHoriz, "More", onClick = { menu = true })
                DropdownMenu(menu, onDismissRequest = { menu = false }, containerColor = TColor.surfaceRaised) {
                    actions.menu.forEach { a ->
                        val c = if (a.destructive) TColor.red else TColor.textPrimary
                        DropdownMenuItem(
                            text = { Text(a.label, color = c) }, leadingIcon = { Icon(a.icon, null, tint = c) },
                            onClick = { menu = false; a.run() },
                        )
                    }
                }
            }
            CircleIcon(Icons.Filled.Close, "Close", onClick = actions.close)
        }
    }
}

@Composable
fun TripStatus(s: TripSnapshot, now: LocalDateTime) {
    val title = when (s.phase) {
        TripPhase.UPCOMING -> if (s.start == null) "Not scheduled yet" else when (val d = s.countdownDays(now)) { 0 -> "Starts today"; 1 -> "Starts tomorrow"; else -> "Starts in $d days" }
        TripPhase.NOW -> "Day ${s.dayOfTrip(now)} of ${s.days ?: 1}"
        TripPhase.PAST -> s.end?.let { e ->
            val days = ChronoUnit.DAYS.between(e.toLocalDate(), now.toLocalDate())
            if (days < 60) "Completed $days days ago" else "Completed ${Fmt.monthDayYear(e)}"
        } ?: "Completed"
    }
    val sub = buildList {
        s.days?.let { add(if (it == 1) "1 day" else "$it days") }
        add(s.routeCodes)
        if (s.phase == TripPhase.UPCOMING) s.events.firstOrNull { it.date != null }?.let { e ->
            add("${if (e.kind == EventKind.DEPARTURE) "Departs" else "Starts"} ${Fmt.time(e.date!!)}")
        }
    }.joinToString(" • ")
    StatusBanner(title, sub, if (s.phase == TripPhase.NOW) TColor.green else Color(0xFFD1D1D6))
}

@Composable
private fun JourneyLink(j: ApiJourney, tripId: Int, actions: TripDetailActions) {
    Row(
        Modifier.padding(top = 12.dp).fillMaxWidth().clip(RoundedCornerShape(14.dp)).background(TColor.blue.copy(alpha = 0.10f))
            .plainClick { actions.openJourney(j.id) }.padding(12.dp),
        verticalAlignment = Alignment.CenterVertically,
    ) {
        Icon(Icons.Filled.Layers, null, tint = TColor.blue)
        Column(Modifier.weight(1f).padding(horizontal = 12.dp)) {
            MicroLabel("Part of a journey")
            Text(j.title.ifBlank { "Journey" }, style = TType.calloutStrong, color = TColor.textPrimary, maxLines = 1)
        }
        val pos = j.tripIds.indexOf(tripId)
        if (pos >= 0) Text("Leg ${pos + 1} of ${maxOf(j.tripCount, j.tripIds.size)}", style = TType.footnote, color = TColor.textSecondary)
        Icon(Icons.AutoMirrored.Filled.KeyboardArrowRight, null, tint = TColor.textTertiary)
    }
}

@Composable
private fun Travelers(s: TripSnapshot) {
    val people = s.trip.participants
    Column {
        Row(verticalAlignment = Alignment.Bottom) {
            Text("Travelers", style = TType.title3, color = TColor.textPrimary)
            Text("  ${people.size}", style = TType.number, color = TColor.textTertiary)
        }
        Spacer(Modifier.height(12.dp))
        if (people.isEmpty()) {
            Row(verticalAlignment = Alignment.CenterVertically) {
                Box(Modifier.size(48.dp).clip(CircleShape).background(TColor.surfaceRaised), Alignment.Center) { Icon(Icons.Filled.Add, null, tint = TColor.textPrimary) }
                Column(Modifier.padding(start = 12.dp)) {
                    Text("Who's coming?", style = TType.headline, color = TColor.textPrimary)
                    Text("Add people by name to split costs", style = TType.footnote, color = TColor.textSecondary)
                }
            }
        } else Row(Modifier.horizontalScroll(rememberScrollState()), horizontalArrangement = Arrangement.spacedBy(14.dp)) {
            people.forEach { p ->
                Column(Modifier.width(60.dp), horizontalAlignment = Alignment.CenterHorizontally) {
                    Box(Modifier.size(48.dp).clip(CircleShape).background(avatarColor(p.id)), Alignment.Center) {
                        Text(p.initials, style = TType.headline, color = Color.White)
                    }
                    Text(p.name.substringBefore(" "), style = TType.caption, color = TColor.textPrimary, maxLines = 1, modifier = Modifier.padding(top = 5.dp))
                    if (p.id == s.trip.ownerId) Text("Organizer", style = TType.micro, color = TColor.textSecondary)
                }
            }
        }
    }
}

private val avatarPalette = listOf(0xFF5E5CE6, 0xFF30B0C7, 0xFFFF7A59, 0xFF34C759, 0xFFFF9F0A, 0xFFBF5AF2, 0xFF0A84FF)
fun avatarColor(id: Int): Color = Color(avatarPalette[Math.floorMod(id, avatarPalette.size)])

