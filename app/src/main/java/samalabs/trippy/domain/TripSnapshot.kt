package samalabs.trippy.domain

import samalabs.trippy.data.ApiFlight
import samalabs.trippy.data.ApiLodging
import samalabs.trippy.data.ApiRentalCar
import samalabs.trippy.data.ApiTrip
import java.time.Instant
import java.time.LocalDateTime
import java.time.ZoneId
import java.time.temporal.ChronoUnit

enum class TripPhase(val label: String) { NOW("Now"), UPCOMING("Upcoming"), PAST("Past") }

enum class EventKind { DEPARTURE, ARRIVAL, PICKUP, DROPOFF, ACTIVITY, STAY }

enum class HighlightKind { SEAT, CONFIRMATION, PLATE, MILES }

/** One row of the unified itinerary: a takeoff, landing, pickup, return, plan or hotel stay. */
data class TripEvent(
    val id: String,
    val kind: EventKind,
    val date: LocalDateTime?,
    val code: String,
    val city: String?,
    val coordinate: LatLng?,
    /** Small uppercase line above the big time, e.g. "UNITED UA 837" or "PICK UP · HERTZ". */
    val micro: String,
    val title: String,
    val subtitle: String?,
    val highlight: String? = null,
    val highlightKind: HighlightKind? = null,
    val flight: ApiFlight? = null,
    val rental: ApiRentalCar? = null,
    val lodging: ApiLodging? = null,
    /** Where [date] (a local wall-clock time) happens; used to sort by real time. */
    val zone: ZoneId? = null,
) {
    val instant: Instant? get() = date?.atZone(zone ?: ZoneId.systemDefault())?.toInstant()
}

data class TripStop(val code: String, val city: String?, val coordinate: LatLng?)

const val AUTO_MARKER = "Auto-generated from rental history"

val ApiTrip.isAutoGenerated: Boolean get() = description.orEmpty().startsWith(AUTO_MARKER) || title.endsWith("(auto)")
val ApiTrip.displayTitle: String get() = (if (title.endsWith(" (auto)")) title.dropLast(7) else title).ifBlank { "Untitled trip" }
val ApiTrip.activeLodgings: List<ApiLodging> get() = lodgings.filterNot { it.isCancelled }

/** Rentals linked by trip_id, plus unassigned rentals picked up inside the trip window. */
fun ApiTrip.linkedRentals(all: List<ApiRentalCar>): List<ApiRentalCar> {
    val byId = LinkedHashMap<Int, ApiRentalCar>()
    rentalCars.forEach { byId[it.id] = it }
    all.filter { it.tripId == id }.forEach { byId[it.id] = it }
    val s = Fmt.parse(startDate)
    val e = Fmt.parse(endDate)
    if (s != null && e != null) {
        val from = s.minusHours(12)
        val to = e.plusHours(36)
        all.filter { it.tripId == null }.forEach { r ->
            val p = r.pickupDate
            if (p != null && !p.isBefore(from) && !p.isAfter(to)) byId[r.id] = r
        }
    }
    return byId.values.sortedBy { it.pickupDate ?: LocalDateTime.MAX }
}

fun ApiTrip.events(allRentals: List<ApiRentalCar>): List<TripEvent> {
    val out = mutableListOf<TripEvent>()
    for (f in flights) {
        val dep = f.departureDate
        val arr = f.arrivalDate
        val sub = buildList {
            if (arr != null) add("Arrives ${f.toCode} ${Fmt.time(arr)}")
            f.durationText?.let(::add)
            DisplayName.cabin(f.cabinClass)?.let(::add)
        }
        out += TripEvent(
            id = "f${f.id}-d", kind = EventKind.DEPARTURE, date = dep, code = f.fromCode,
            city = Airports.city(f.fromCode), coordinate = Airports.coordinate(f.fromCode),
            micro = "${f.airline.orEmpty()} ${f.number}".trim().uppercase(),
            title = "Depart ${Airports.city(f.fromCode) ?: f.fromCode}",
            subtitle = sub.joinToString(" · ").ifEmpty { null },
            highlight = f.seat?.let { "Seat $it" } ?: f.confirmationNumber,
            highlightKind = if (f.seat != null) HighlightKind.SEAT else HighlightKind.CONFIRMATION,
            flight = f, zone = Airports.zone(f.fromCode),
        )
        out += TripEvent(
            id = "f${f.id}-a", kind = EventKind.ARRIVAL, date = arr, code = f.toCode,
            city = Airports.city(f.toCode), coordinate = Airports.coordinate(f.toCode),
            micro = "LAND · ${f.number}".uppercase(),
            title = "Arrive ${Airports.city(f.toCode) ?: f.toCode}",
            subtitle = DisplayName.flightStatus(f.status),
            flight = f, zone = Airports.zone(f.toCode),
        )
    }
    for (r in linkedRentals(allRentals)) {
        val pCity = Airports.city(r.pickupDisplayCode) ?: r.pickupDisplayCity
        val dCity = Airports.city(r.dropoffDisplayCode) ?: r.dropoffDisplayCity
        val brand = r.companyName.uppercase()
        out += TripEvent(
            id = "r${r.id}-p", kind = EventKind.PICKUP, date = r.pickupDate, code = r.pickupDisplayCode, city = pCity,
            coordinate = r.pickupCoordinate ?: Airports.coordinate(r.pickupDisplayCode),
            micro = "PICK UP · $brand", title = r.vehicleName,
            subtitle = listOfNotNull(pCity, r.rentalDays?.let { if (it == 1) "1 day" else "$it days" }).joinToString(" · "),
            highlight = r.licensePlate ?: r.confirmationText ?: DisplayName.vehicleClass(r.vehicleClass),
            highlightKind = if (r.licensePlate != null) HighlightKind.PLATE else HighlightKind.CONFIRMATION,
            rental = r, zone = Airports.zone(r.pickupDisplayCode) ?: r.pickupCoordinate?.let(Airports::zone),
        )
        if (r.dropoffDate != null || r.isOneWay) {
            out += TripEvent(
                id = "r${r.id}-d", kind = EventKind.DROPOFF, date = r.dropoffDate, code = r.dropoffDisplayCode, city = dCity,
                coordinate = r.dropoffCoordinate ?: Airports.coordinate(r.dropoffDisplayCode) ?: r.pickupCoordinate,
                micro = "RETURN · $brand",
                title = if (r.isOneWay) "Drop off in $dCity" else "Return to ${r.dropoffDisplayCode}",
                subtitle = r.costText?.let { "Total $it" },
                highlight = r.milesDriven?.let { "${Fmt.number(it)} mi" },
                highlightKind = r.milesDriven?.let { HighlightKind.MILES },
                rental = r, zone = Airports.zone(r.dropoffDisplayCode) ?: r.dropoffCoordinate?.let(Airports::zone),
            )
        }
    }
    for (a in activities) {
        out += TripEvent(
            id = "a${a.id}", kind = EventKind.ACTIVITY, date = Fmt.parse(a.startTime), code = "", city = null,
            coordinate = null, micro = "PLAN", title = a.title, subtitle = a.description,
        )
    }
    // Stays: one row at check-in. An empty code keeps them off the flight/drive route.
    for (h in lodgings) {
        out += TripEvent(
            id = "h${h.id}", kind = EventKind.STAY, date = h.checkInDate, code = "", city = h.city,
            coordinate = h.coordinate, micro = h.microLine, title = h.displayName, subtitle = null, lodging = h,
            zone = h.checkInTz?.let { runCatching { ZoneId.of(it) }.getOrNull() } ?: h.coordinate?.let(Airports::zone),
        )
    }
    return timelineOrder(out)
}

/**
 * Real-time order (each wall-clock time in its own zone). A landing never sorts above its own
 * takeoff, and a check-in never sorts above a flight landing the same local day.
 */
fun timelineOrder(events: List<TripEvent>): List<TripEvent> {
    val key = HashMap<String, Instant>()
    events.forEach { key[it.id] = it.instant ?: Instant.MAX }
    for (e in events.filter { it.kind == EventKind.ARRIVAL }) {
        val dep = key[e.id.dropLast(2) + "-d"]
        val a = key[e.id]
        if (dep != null && a != null && dep != Instant.MAX && !a.isAfter(dep)) key[e.id] = dep.plusSeconds(1)
    }
    for (e in events.filter { it.kind == EventKind.STAY }) {
        val d = e.date ?: continue
        val last = events.filter { it.kind == EventKind.ARRIVAL && it.date?.toLocalDate() == d.toLocalDate() }
            .mapNotNull { key[it.id] }.maxOrNull()
        val mine = key[e.id]
        if (last != null && mine != null && !mine.isAfter(last)) key[e.id] = last.plusSeconds(1)
    }
    return events.withIndex().sortedWith(compareBy<IndexedValue<TripEvent>> { key[it.value.id] }.thenBy { it.index }).map { it.value }
}

/** Ordered distinct places, consecutive duplicates collapsed. */
fun stops(events: List<TripEvent>): List<TripStop> {
    val out = mutableListOf<TripStop>()
    for (e in events) {
        if (e.code.isEmpty()) continue
        val coord = e.coordinate ?: Airports.coordinate(e.code)
        val last = out.lastOrNull()
        if (last != null && last.code == e.code) {
            if (last.coordinate == null && coord != null) out[out.lastIndex] = last.copy(city = last.city ?: e.city, coordinate = coord)
            continue
        }
        out += TripStop(e.code, e.city ?: Airports.city(e.code), coord)
    }
    return out
}

/** One trip with everything derived from it, computed once per render. */
class TripSnapshot(val trip: ApiTrip, allRentals: List<ApiRentalCar>, now: LocalDateTime) {
    val rentals: List<ApiRentalCar> = trip.linkedRentals(allRentals)
    val events: List<TripEvent> = trip.events(allRentals)
    val stops: List<TripStop> = stops(events)
    val start: LocalDateTime? = Fmt.parse(trip.startDate) ?: events.mapNotNull { it.date }.minOrNull()
    val end: LocalDateTime? = Fmt.parse(trip.endDate) ?: events.mapNotNull { it.date }.maxOrNull()
    val phase: TripPhase = when {
        start == null -> TripPhase.UPCOMING
        now.isBefore(start) -> TripPhase.UPCOMING
        !now.isAfter((end ?: start).toLocalDate().plusDays(1).atStartOfDay()) -> TripPhase.NOW
        else -> TripPhase.PAST
    }
    val id: Int get() = trip.id

    val routeCodes: String
        get() {
            var codes = stops.map { it.code }
            if (codes.isEmpty()) {
                // Hotel-only trips: the stay cities in check-in order.
                codes = trip.activeLodgings.sortedBy { it.checkIn.orEmpty() }.mapNotNull { it.city?.trim()?.takeIf(String::isNotEmpty) }.distinct()
            }
            return when {
                codes.isEmpty() -> "No places yet"
                codes.size <= 4 -> codes.joinToString(" → ")
                else -> codes.take(3).joinToString(" → ") + " → +${codes.size - 3}"
            }
        }

    /** Whole days covered, counting both ends ("Nov 1 – 15" = 15 days). */
    val days: Int?
        get() {
            val s = start ?: return null
            val e = end ?: s
            return maxOf(1, ChronoUnit.DAYS.between(s.toLocalDate(), e.toLocalDate()).toInt() + 1)
        }

    val year: Int get() = start?.year ?: 0

    /** Expenses when logged; otherwise what the bookings cost. */
    val spend: Double
        get() = if (trip.expenses.isNotEmpty()) trip.expenses.sumOf { it.amount }
        else rentals.sumOf { it.cost ?: 0.0 } + trip.flights.sumOf { it.cost ?: 0.0 } + trip.activeLodgings.sumOf { it.cost ?: 0.0 }

    fun dateRange(withYear: Boolean = false): String? {
        val s = start ?: return null
        val e = end ?: s
        val tail = if (withYear) ", ${e.year}" else ""
        return when {
            s.toLocalDate() == e.toLocalDate() -> Fmt.monthDay(s) + tail
            s.year == e.year && s.month == e.month -> "${Fmt.monthDay(s)}–${e.dayOfMonth}$tail"
            else -> "${Fmt.monthDay(s)} – ${Fmt.monthDay(e)}$tail"
        }
    }

    /** Days until start (upcoming) or days left (now). */
    fun countdownDays(now: LocalDateTime): Int {
        val target = (if (phase == TripPhase.UPCOMING) start else end) ?: return 0
        return maxOf(0, ChronoUnit.DAYS.between(now.toLocalDate(), target.toLocalDate()).toInt())
    }

    fun dayOfTrip(now: LocalDateTime): Int {
        val s = start ?: return 1
        return ChronoUnit.DAYS.between(s.toLocalDate(), now.toLocalDate()).toInt() + 1
    }

    /** First departure still ahead, for "Departs 6:38 AM" lines. */
    fun nextDeparture(now: LocalDateTime): TripEvent? =
        events.firstOrNull { it.kind == EventKind.DEPARTURE && it.date?.isAfter(now) == true }
}

/** Trips list buckets, as on iOS: journeys pull their legs out, pinned trips float up. */
data class TripSections(
    val hero: TripSnapshot?,
    val pinned: List<TripSnapshot>,
    val now: List<TripSnapshot>,
    val upcoming: List<TripSnapshot>,
    val pastByYear: List<Pair<Int, List<TripSnapshot>>>,
) {
    companion object {
        fun of(all: List<TripSnapshot>, journeyTripIds: Set<Int>): TripSections {
            val free = all.filterNot { it.id in journeyTripIds }
            val pinned = free.filter { it.trip.pinned }.sortedBy { it.start ?: LocalDateTime.MAX }
            val rest = free.filterNot { it.trip.pinned }
            val current = rest.filter { it.phase == TripPhase.NOW }.sortedBy { it.start ?: LocalDateTime.MIN }
            val upcoming = rest.filter { it.phase == TripPhase.UPCOMING }.sortedBy { it.start ?: LocalDateTime.MAX }
            val past = rest.filter { it.phase == TripPhase.PAST }.sortedByDescending { it.start ?: LocalDateTime.MIN }
            val hero = current.firstOrNull() ?: upcoming.firstOrNull()
            val years = past.groupBy { it.year }.toList().sortedByDescending { it.first }
            return TripSections(
                hero = hero,
                pinned = pinned,
                now = current.filter { it.id != hero?.id },
                upcoming = upcoming.filter { it.id != hero?.id },
                pastByYear = years,
            )
        }
    }
}

/** "52 trips · 238 days away · 19 places · $15.9k". */
fun statsLine(all: List<TripSnapshot>): String {
    val days = all.filter { it.phase != TripPhase.UPCOMING }.sumOf { it.days ?: 0 }
    val places = all.flatMap { s -> s.stops.map { it.city ?: it.code } }.toSet().size
    val spent = all.sumOf { it.spend }
    return "${all.size} trip${if (all.size == 1) "" else "s"} · $days days away · $places places · ${Fmt.compactMoney(spent)}"
}
